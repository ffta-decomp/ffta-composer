let locale = 'zh-CN';

export function setLanguage(language) {
  locale = language === 'en' ? 'en' : 'zh-CN';
  return locale;
}

export function t(key) {
  return locale === 'en' ? english[key] ?? key : key;
}

export function tr(strings, ...values) {
  const key = strings.reduce((result, part, i) => result + (i ? `{${i - 1}}` : '') + part, '');
  return t(key).replace(/\{(\d+)\}/g, (_, index) => values[Number(index)]);
}

// Capture the authoring language of the static shell once. Dynamic panels
// call t()/tr() when rendered, so the active document never becomes a source.
export function localizeShell(body) {
  const walking = document.createTreeWalker(body, NodeFilter.SHOW_TEXT);
  const text = [];
  while (walking.nextNode()) {
    const node = walking.currentNode;
    const source = node.nodeValue.trim();
    if (/[\u3400-\u9fff]/.test(source)) text.push({ node, source, original: node.nodeValue });
  }
  const attributes = ['aria-label', 'placeholder'].flatMap(name =>
    [...body.querySelectorAll(`[${name}]`)].map(node => ({ node, name, source: node.getAttribute(name) })));
  const title = document.title;
  return language => {
    document.documentElement.lang = setLanguage(language);
    document.title = t(title);
    for (const { node, source, original } of text) node.nodeValue = original.replace(source, t(source));
    for (const { node, name, source } of attributes) node.setAttribute(name, t(source));
  };
}
