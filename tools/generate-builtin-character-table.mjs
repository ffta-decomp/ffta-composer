import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {check} from '../src/binary.mjs';

const [source,output]=process.argv.slice(2);
check(source&&output,'Usage: generate-builtin-character-table SOURCE_JSON OUTPUT_MODULE');
const bytes=await readFile(source),hash=createHash('sha256').update(bytes).digest('hex');
check(hash==='635686a3b23aa786ff6ab0e289e1bd2fe875d31252ba556ebd9095ea5ee342cf','Expected the reviewed owner-supplied US Chinese v1.1 mapping');
const {glyphs}=JSON.parse(bytes);
check(glyphs.length===3175&&glyphs.every((g,i)=>g.index===i&&(g.unicode===null||typeof g.unicode==='string')),'Invalid native glyph mapping');
const labels=glyphs.map(g=>g.unicode),lines=[];
for(let i=0;i<labels.length;i+=16)lines.push('  '+JSON.stringify(labels.slice(i,i+16)).slice(1,-1));
const text=`// Owner-supplied US Chinese v1.1 token-to-Unicode labels. See NOTICE.\n// Converted from 美版汉化字符表.xlsx; mapping provenance does not assign a license.\n// Source JSON SHA-256: ${hash}\n// Workbook SHA-256: 473dd8d2bb43c17aab292a51e00fa5154b97bc5610d53cded1cb737d6d02e17e\n// No font pixels, ROM data, translations, or executable code are embedded here.\n// Generated by tools/generate-builtin-character-table.mjs; nulls and aliases are intentional.\nexport const US_CN_V11_LABELS = Object.freeze([\n${lines.join(',\n')}\n]);\n`;
await writeFile(output,text);
